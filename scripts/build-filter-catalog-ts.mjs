import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const root = path.resolve(__dirname, "..")

const manifestPath = path.join(root, "public", "banks", "final-2026", "manifest.json")
const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf-8"))

const difficultyMap = {
  easy: { value: 1, band: "BASIC" },
  medium: { value: 2, band: "MEDIUM" },
  hard: { value: 4, band: "HARD" },
  expert: { value: 5, band: "EXPERT" },
}

function typeForFamily(family) {
  if (family === "true_false") return "true_false"
  if (family === "fill_choice") return "fill_blank"
  return "single_choice"
}

const catalog = []

for (const shard of manifest.shards) {
  const shardPath = path.join(root, "public", shard.questions_file)
  const rows = JSON.parse(fs.readFileSync(shardPath, "utf-8"))
  const work = shard.chapter.startsWith("DAN") ? "Daniel" : "Profetas y Reyes"
  const chapterNum = Number(shard.chapter.match(/\d+/)?.[0] ?? 0)

  for (const raw of rows) {
    const diff = difficultyMap[raw.difficulty] ?? { value: 2, band: "MEDIUM" }
    const tier = raw.tier ?? (diff.band === "HARD" || diff.band === "EXPERT" ? "COMPETITIVE_ACCEPT" : "COVERAGE_ACCEPT")
    const provisional = Boolean(raw.provisional)
    const blind = raw.blind_pool !== null && raw.blind_pool !== undefined

    catalog.push({
      id: raw.id,
      factId: raw.fact_id,
      sourceUnitId: raw.source_unit_id,
      work,
      chapter: chapterNum,
      type: typeForFamily(raw.family),
      family: raw.family,
      difficulty: diff.value,
      difficultyBand: diff.band,
      tier,
      provisional,
      blind,
    })
  }
}

const targetDir = path.join(root, "src", "data")
if (!fs.existsSync(targetDir)) {
  fs.mkdirSync(targetDir, { recursive: true })
}

const targetFile = path.join(targetDir, "filter-catalog.ts")
const content = `// Auto-generated by scripts/build-filter-catalog-ts.mjs - DO NOT EDIT MANUALLY
export type FilterCatalogItem = {
  id: string
  factId: string
  sourceUnitId: string
  work: "Daniel" | "Profetas y Reyes"
  chapter: number
  type: "single_choice" | "fill_blank" | "true_false"
  family: string
  difficulty: number
  difficultyBand: "BASIC" | "MEDIUM" | "HARD" | "EXPERT"
  tier: "COMPETITIVE_ACCEPT" | "COVERAGE_ACCEPT"
  provisional: boolean
  blind: boolean
}

export const FINAL_FILTER_CATALOG: FilterCatalogItem[] = ${JSON.stringify(catalog, null, 2)}
`

fs.writeFileSync(targetFile, content, "utf-8")
console.log(`Generated ${targetFile} with ${catalog.length} items`)
